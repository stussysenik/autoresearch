"""
Pydantic models for tag calibration experiment.
"""

from __future__ import annotations
from pydantic import BaseModel, Field


class Card(BaseModel):
    """A card from the mymind-clone-web database."""
    id: str
    type: str = "article"
    title: str | None = None
    content: str | None = None
    url: str | None = None
    image_url: str | None = None
    tags: list[str] = Field(default_factory=list)
    metadata: dict = Field(default_factory=dict)
    created_at: str | None = None

    @property
    def platform(self) -> str:
        return self.metadata.get("platform", "unknown")

    def content_preview(self, max_len: int = 1500) -> str:
        """Truncated content for LLM prompts."""
        text = self.content or ""
        return text[:max_len] + "..." if len(text) > max_len else text


class TaxonomyCategory(BaseModel):
    """A single category within the taxonomy (e.g., primary, contextual, style)."""
    name: str
    description: str
    vocabulary: list[str] = Field(default_factory=list)
    min_tags: int = 1
    max_tags: int = 2
    rules: list[str] = Field(default_factory=list)


class Taxonomy(BaseModel):
    """The full discovered taxonomy for tagging cards."""
    version: str = "1.0"
    description: str = ""
    categories: list[TaxonomyCategory] = Field(default_factory=list)
    blocked_tags: list[str] = Field(default_factory=list)
    platform_guidelines: dict[str, str] = Field(default_factory=dict)

    def get_category(self, name: str) -> TaxonomyCategory | None:
        for cat in self.categories:
            if cat.name == name:
                return cat
        return None

    def all_vocabulary(self) -> set[str]:
        """All valid tags across all categories."""
        result: set[str] = set()
        for cat in self.categories:
            result.update(cat.vocabulary)
        return result

    def blocked_set(self) -> set[str]:
        return set(self.blocked_tags)


class GoldTag(BaseModel):
    """Gold-standard tags for a single card, generated by GLM 4.7."""
    card_id: str
    tags: dict[str, list[str]] = Field(default_factory=dict)  # category_name -> [tags]
    flat_tags: list[str] = Field(default_factory=list)
    reasoning: str | None = None
    confidence: float = 0.0

    @classmethod
    def from_categorized(cls, card_id: str, categorized_tags: dict[str, list[str]],
                         reasoning: str | None = None, confidence: float = 0.85) -> GoldTag:
        """Build from per-category tag dict, auto-flattening."""
        flat = []
        for tags in categorized_tags.values():
            flat.extend(tags)
        return cls(
            card_id=card_id,
            tags=categorized_tags,
            flat_tags=flat,
            reasoning=reasoning,
            confidence=confidence,
        )


class ValidationMetrics(BaseModel):
    """Metrics from comparing Gemma predictions against gold tags."""
    total_cards: int = 0
    micro_f1: float = 0.0
    macro_f1: float = 0.0
    exact_match_rate: float = 0.0
    taxonomy_adherence: float = 0.0
    style_coverage: float = 0.0
    blocked_tag_rate: float = 0.0
    per_platform: dict[str, float] = Field(default_factory=dict)
    per_category: dict[str, dict[str, float]] = Field(default_factory=dict)
